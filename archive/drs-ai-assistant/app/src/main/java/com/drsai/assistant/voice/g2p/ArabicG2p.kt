package com.drsai.assistant.voice.g2p

// ArabicG2p.kt — dependency-free Arabic G2P front-end for Nabra-Saudi-7M (Kokoro/StyleTTS2, 24 kHz).
//
// Reproduces the training front-end of oddadmix/Nabra-Saudi-7M (load_model.py):
//   text.replace(U+0640,"") -> arabic_g2p.normalize_text -> misaki EspeakG2P("ar")
//   (espeak-ng 1.52, phonemizer preserve_punctuation, tie '^' -> ʤ/ʧ/...) -> clean_phonemes
//   -> config.json vocab + EXTRA_SYMBOLS (ʕ=7, ħ=8).
//
// espeak-ng output for this voice was verified to be word-separable (phonemizing each
// whitespace word alone and joining with ' ' reproduces the sentence output on all test
// vectors), so this port works word by word:
//   1. LEXICON  : exact espeak-ng output for ~71k word forms (all ar_list/ar_listx entries +
//                 OpenSubtitles top-50k Arabic forms) shipped as a TSV asset (word \t phonemes).
//   2. NUMBERS  : exact espeak-ng output for 0..1000 and 1900..2100 (numbers.tsv asset).
//   3. AL-PREFIX: (و|ب|ف|ك)?ال + stem-in-lexicon -> exact espeak prefix form + stem.
//   4. RULES    : approximation of espeak-ng's ar_rules + SetWordStress(STRESSPOSN_3R) for
//                 everything else. Not bit-exact for every out-of-lexicon word (see SPEC.md).
//
// Data provenance: lexicon/number strings are generated by espeak-ng (GPL-3.0) from its
// ar_list/ar_listx/ar_rules data; treat the asset files as GPL-3.0-derived data.
//
// Usage:
//   val g2p = ArabicG2p.load(context.assets.open("nabra_lexicon.tsv"), context.assets.open("nabra_numbers.tsv"))
//   val r = g2p.encode("الطقس اليوم حلو والسما صافية مرة.")
//   // r.inputIds = [0, ...ids..., 0] (LongArray)  r.styleIndex -> row of af_msa.bin [510 x 256]

import java.io.BufferedReader
import java.io.InputStream
import java.io.InputStreamReader
import java.util.zip.GZIPInputStream

class ArabicG2p(
    private val lexicon: Map<String, String>,
    private val numbers: Map<Int, String> = emptyMap(),
    /** espeak-ng dictionary entries (ar_list/ar_listx): 3rd TSV column "d", or "D" when the
     *  dictionary entry carries an explicit stress mark. Value = true for "D". */
    private val dictWords: Map<String, Boolean> = emptyMap(),
) {
    data class Encoded(
        val phonemes: String,
        /** token ids WITHOUT padding */
        val ids: IntArray,
        /** model input: [0, ids..., 0] */
        val inputIds: LongArray,
        /** row of the voice pack to use as style = phonemes.length - 1 (clamped to 0..509) */
        val styleIndex: Int,
    )

    companion object {
        /** Kokoro/Nabra vocab (config.json) + EXTRA_SYMBOLS ʕ=7, ħ=8. Identical to tokens.txt. */
        val VOCAB: Map<Char, Int> = linkedMapOf(
            ';' to 1, ':' to 2, ',' to 3, '.' to 4, '!' to 5, '?' to 6, 'ʕ' to 7, 'ħ' to 8,
            '—' to 9, '…' to 10, '"' to 11, '(' to 12, ')' to 13, '“' to 14, '”' to 15, ' ' to 16,
            '\u0303' to 17, 'ʣ' to 18, 'ʥ' to 19, 'ʦ' to 20, 'ʨ' to 21, 'ᵝ' to 22, 'ꭧ' to 23,
            'A' to 24, 'I' to 25, 'O' to 31, 'Q' to 33, 'S' to 35, 'T' to 36, 'W' to 39, 'Y' to 41,
            'ᵊ' to 42, 'a' to 43, 'b' to 44, 'c' to 45, 'd' to 46, 'e' to 47, 'f' to 48, 'h' to 50,
            'i' to 51, 'j' to 52, 'k' to 53, 'l' to 54, 'm' to 55, 'n' to 56, 'o' to 57, 'p' to 58,
            'q' to 59, 'r' to 60, 's' to 61, 't' to 62, 'u' to 63, 'v' to 64, 'w' to 65, 'x' to 66,
            'y' to 67, 'z' to 68, 'ɑ' to 69, 'ɐ' to 70, 'ɒ' to 71, 'æ' to 72, 'β' to 75, 'ɔ' to 76,
            'ɕ' to 77, 'ç' to 78, 'ɖ' to 80, 'ð' to 81, 'ʤ' to 82, 'ə' to 83, 'ɚ' to 85, 'ɛ' to 86,
            'ɜ' to 87, 'ɟ' to 90, 'ɡ' to 92, 'ɥ' to 99, 'ɨ' to 101, 'ɪ' to 102, 'ʝ' to 103,
            'ɯ' to 110, 'ɰ' to 111, 'ŋ' to 112, 'ɳ' to 113, 'ɲ' to 114, 'ɴ' to 115, 'ø' to 116,
            'ɸ' to 118, 'θ' to 119, 'œ' to 120, 'ɹ' to 123, 'ɾ' to 125, 'ɻ' to 126, 'ʁ' to 128,
            'ɽ' to 129, 'ʂ' to 130, 'ʃ' to 131, 'ʈ' to 132, 'ʧ' to 133, 'ʊ' to 135, 'ʋ' to 136,
            'ʌ' to 138, 'ɣ' to 139, 'ɤ' to 140, 'χ' to 142, 'ʎ' to 143, 'ʒ' to 147, 'ʔ' to 148,
            'ˈ' to 156, 'ˌ' to 157, 'ː' to 158, 'ʰ' to 162, 'ʲ' to 164, '↓' to 169, '→' to 171,
            '↗' to 172, '↘' to 173, 'ᵻ' to 177,
        )
        const val VOICE_ROWS = 510
        const val MAX_PHONEMES = 510

        private fun reader(input: InputStream): BufferedReader {
            val stream = if (input.markSupported()) input else java.io.BufferedInputStream(input)
            stream.mark(2)
            val b0 = stream.read(); val b1 = stream.read(); stream.reset()
            val src = if (b0 == 0x1f && b1 == 0x8b) GZIPInputStream(stream) else stream
            return BufferedReader(InputStreamReader(src, Charsets.UTF_8))
        }

        /** lexicon TSV: word \t phonemes [\t d]; numbers TSV: int \t phonemes. Plain or gzip. */
        fun load(lexicon: InputStream, numbers: InputStream? = null): ArabicG2p {
            val lex = HashMap<String, String>(1 shl 17)
            val dict = HashMap<String, Boolean>(1 shl 16)
            reader(lexicon).useLines { lines ->
                for (line in lines) {
                    val f = line.split('\t')
                    if (f.size < 2 || f[0].isEmpty()) continue
                    lex[f[0]] = f[1]
                    if (f.size > 2 && (f[2] == "d" || f[2] == "D")) dict[f[0]] = f[2] == "D"
                }
            }
            val num = HashMap<Int, String>()
            if (numbers != null) reader(numbers).useLines { lines ->
                for (line in lines) {
                    val f = line.split('\t')
                    if (f.size >= 2) f[0].toIntOrNull()?.let { num[it] = f[1] }
                }
            }
            return ArabicG2p(lex, num, dict)
        }

        // phonemizer default punctuation marks (preserve_punctuation=True)
        private const val MARKS = ";:,.!?¡¿—…\"«»“”(){}[]"
        private val MARKS_RE = Regex("(\\s*[" + MARKS.map { "\\" + it }.joinToString("") + "]+\\s*)+")
        private val CITATION = Regex("\\[[^\\]]*]")
        private val LATIN = Regex("[A-Za-z]+")
        private val WS = Regex("\\s+")
        private val SYLLABLE_DOT = Regex("(?<=\\S)\\.(?=\\S)")
        // characters that espeak treats as word/clause separators inside a chunk (output nothing)
        private val SEPARATORS = setOf('،', '؛', '؟', '-', '_', '/', '\\', '*', '+', '=', '&', '#', '@', '%', '٪', '^', '~', '|', '<', '>', '\'', '`', '\u200c', '\u200d', '\u200f', '\u200e')
    }

    // ------------------------------------------------------------------ public API

    fun encode(text: String): Encoded {
        var ph = phonemize(text)
        if (ph.length > MAX_PHONEMES) ph = ph.substring(0, MAX_PHONEMES) // Kokoro pipeline truncates at 510
        val ids = ph.mapNotNull { VOCAB[it] }.toIntArray()
        val input = LongArray(ids.size + 2)
        for (i in ids.indices) input[i + 1] = ids[i].toLong()
        val style = (ph.length - 1).coerceIn(0, VOICE_ROWS - 1)
        return Encoded(ph, ids, input, style)
    }

    /** Text -> phoneme string, identical in format to the Python training front-end. */
    fun phonemize(raw: String): String {
        // load_model.py: drop tatweel; arabic_g2p.normalize_text
        var t = raw.replace("\u0640", "")
        t = CITATION.replace(t, " ")
        t = LATIN.replace(t, " ")
        t = WS.replace(t, " ").trim()
        if (t.isEmpty()) return ""
        // misaki EspeakG2P: angles -> curly quotes, parentheses -> angles
        t = t.replace('«', '\u201c').replace('»', '\u201d').replace('(', '«').replace(')', '»')
        var ps = phonemizePreservingPunctuation(t).trim()
        ps = ps.replace("-", "")
        ps = ps.replace('«', '(').replace('»', ')')
        return clean(ps)
    }

    // ------------------------------------------------------------------ phonemizer emulation

    private fun phonemizePreservingPunctuation(line: String): String {
        val matches = MARKS_RE.findAll(line).toList()
        if (matches.isEmpty()) return phonemizeChunk(line)
        if (matches.size == 1 && matches[0].value == line) return line // only punctuation
        // Split into chunks around each mark occurrence (phonemizer Punctuation._preserve_line)
        data class Mark(val text: String, val pos: Char)
        val marks = matches.mapIndexed { i, m ->
            val p = when {
                i == 0 && line.startsWith(m.value) -> 'B'
                i == matches.size - 1 && line.endsWith(m.value) -> 'E'
                else -> 'I'
            }
            Mark(m.value, p)
        }
        val chunks = ArrayList<String>()
        var rest = line
        for (m in marks) {
            val idx = rest.indexOf(m.text)
            chunks.add(rest.substring(0, idx)); rest = rest.substring(idx + m.text.length)
        }
        chunks.add(rest)
        val phon = ArrayDeque(chunks.filter { it.isNotEmpty() }.map { phonemizeChunk(it) })
        // Punctuation.restore with sep.word=' ' strip=False, then caller strips.
        val out = StringBuilder()
        var pendingText: String? = null
        val markQueue = ArrayDeque(marks)
        var done = false
        while (!done) {
            if (markQueue.isEmpty()) {
                if (pendingText != null) { out.append(pendingText); pendingText = null }
                while (phon.isNotEmpty()) out.append(phon.removeFirst()).append(' ')
                done = true
            } else if (pendingText == null && phon.isEmpty()) {
                out.append(markQueue.joinToString("") { it.text }); markQueue.clear(); done = true
            } else {
                val m = markQueue.removeFirst()
                val cur = pendingText ?: phon.removeFirst()
                pendingText = null
                when (m.pos) {
                    'B' -> pendingText = m.text + cur
                    'E' -> { out.append(cur).append(m.text); if (!m.text.endsWith(" ")) out.append(' ') }
                    else -> pendingText = if (phon.isEmpty()) cur + m.text else cur + m.text + phon.removeFirst()
                }
            }
        }
        return out.toString()
    }

    /** One punctuation-free chunk: words separated by spaces (espeak joins clauses with ' '). */
    private fun phonemizeChunk(chunk: String): String {
        val words = ArrayList<String>()
        val sb = StringBuilder()
        fun flush() { if (sb.isNotEmpty()) { words.add(sb.toString()); sb.setLength(0) } }
        for (raw in chunk) {
            val c = mapDigit(raw)
            when {
                c.isWhitespace() || c in SEPARATORS -> flush()
                c.isDigit() -> { if (sb.isNotEmpty() && !sb.last().isDigit()) flush(); sb.append(c) }
                else -> { if (sb.isNotEmpty() && sb.last().isDigit()) flush(); sb.append(c) }
            }
        }
        flush()
        return words.mapNotNull { w -> word(w).takeIf { it.isNotEmpty() } }.joinToString(" ")
    }

    private fun mapDigit(c: Char): Char = when (c) {
        in '\u0660'..'\u0669' -> '0' + (c - '\u0660')
        in '\u06F0'..'\u06F9' -> '0' + (c - '\u06F0')
        else -> c
    }

    // ------------------------------------------------------------------ words

    fun word(w: String): String {
        lexicon[w]?.let { return it }
        return oovWord(w)
    }

    /** Word not in the lexicon (also used for held-out evaluation). */
    fun oovWord(w: String): String {
        if (w.all { it in '0'..'9' }) return number(w)
        alPrefix(w)?.let { return it }
        return Rules.word(w, lexicon, dictWords)
    }

    private fun number(d: String): String {
        val n = d.trimStart('0').ifEmpty { "0" }
        if (n.length <= 4) numbers[n.toInt()]?.let { return it }
        // Not in the table: read digit by digit (espeak would read the full number).
        return d.map { numbers[it - '0'] ?: "" }.filter { it.isNotEmpty() }.joinToString(" ")
    }

    private fun alPrefix(w: String): String? {
        for ((pre, ipa) in AL_PREFIXES) {
            if (w.length > pre.length + 1 && w.startsWith(pre)) {
                val stem = w.substring(pre.length)
                val stemPh = lexicon[stem] ?: Rules.word(stem, lexicon, dictWords)
                val first = stem[0]
                val head = when {
                    pre == "ال" && first !in SUN && first !in MOON -> "al"   // espeak: _) ال (P2 %al
                    first == 'ط' && pre == "ال" -> "ʔa"
                    else -> ipa + (SUN[first] ?: "l")
                }
                return head + stemPh
            }
        }
        return null
    }

    private val AL_PREFIXES = listOf("وال" to "wa", "بال" to "bi", "فال" to "fa", "كال" to "ka", "ال" to "ʔa")
    private val MOON = setOf('ق', 'ف', 'غ', 'ع', 'ه', 'خ', 'ح', 'ج', 'ي', 'ب', 'م', 'ك', 'و', 'إ', 'أ', 'ء')
    private val SUN = mapOf(
        'ت' to "t", 'ث' to "θ", 'د' to "d", 'ذ' to "ð", 'ر' to "r", 'ز' to "z", 'س' to "s",
        'ش' to "ʃ", 'ص' to "s", 'ض' to "d", 'ظ' to "ð", 'ن' to "n", 'ل' to "l", 'ط' to "t",
    )

    private fun clean(ps: String): String {
        var s = SYLLABLE_DOT.replace(ps, "")
        s = s.replace("\u032A", "").replace("ˤ", "").replace("[", "").replace("]", "")
            .replace("{", "").replace("}", "")
        return s
    }

    // ------------------------------------------------------------------ rule fallback

    /**
     * Approximation of espeak-ng's Arabic letter rules (dictsource/ar_rules) and
     * SetWordStress() for stressRule 4 (STRESSPOSN_3R, antepenultimate) with the default
     * Arabic stress flags. Used only for words missing from the lexicon.
     */
    internal object Rules {
        private const val FATHA = '\u064E'; private const val DAMMA = '\u064F'; private const val KASRA = '\u0650'
        private const val SHADDA = '\u0651'; private const val SUKUN = '\u0652'
        private const val FATHATAN = '\u064B'; private const val DAMMATAN = '\u064C'; private const val KASRATAN = '\u064D'
        private const val SUPER_ALEF = '\u0670'

        private val CONS = mapOf(
            'ب' to "b", 'پ' to "p", 'ت' to "t", 'ث' to "θ", 'ج' to "ʤ", 'ح' to "ħ", 'خ' to "χ",
            'د' to "d", 'ذ' to "ð", 'ر' to "r", 'ز' to "z", 'س' to "s", 'ش' to "ʃ", 'ص' to "s",
            'ض' to "d", 'ط' to "t", 'ظ' to "ð", 'ع' to "ʕ", 'غ' to "ɣ", 'ف' to "f", 'ق' to "q",
            'ك' to "k", 'ل' to "l", 'م' to "m", 'ن' to "n", 'ه' to "h", 'ء' to "ʔ", 'أ' to "ʔ",
            'إ' to "ʔ", 'ئ' to "ʔ", 'ؤ' to "ʔ", 'ة' to "t", 'گ' to "g", 'ٱ' to "",
        )
        private val THICK = setOf('ص', 'ض', 'ط', 'ظ')
        // L30 (non-thick consonants) ∪ F (thick): a following ا/و/ي is a long vowel
        private val CONSONANT_LETTERS = CONS.keys - 'ٱ' - 'ق' 
        private val HARAKAT = setOf(FATHA, DAMMA, KASRA)
        private val LENGTHEN_COLON = setOf('ب', 'ت', 'ج', 'د', 'ص', 'ط', 'ق', 'ك', 'ء', 'أ', 'إ', 'ئ', 'ؤ', 'پ', 'گ', 'ة')
        private fun lastLetter(w: String, i: Int): Char {
            var k = i - 1
            while (k >= 0 && w[k] in '\u064B'..'\u0652') k--
            return if (k >= 0) w[k] else '_'
        }
        private val INITIAL_UNSTRESSED = setOf('ب', 'س', 'ف', 'ك', 'ل', 'و')

        /** Segment: ipa text, vowel flag, stress mark (-1 none, 1 = espeak '%' unstressed, 4 = primary).
         *  A segment with empty ipa and vowel=false is a bare stress marker for the next vowel. */
        class Seg(val ipa: String, val vowel: Boolean, var mark: Int = -1)

        private val SUFFIXES: List<Pair<String, List<Seg>>> = listOf(
            "يات" to listOf(Seg("i", true, 4), Seg("jj", false), Seg("aː", true), Seg("t", false)),
            "يون" to listOf(Seg("i", true, 4), Seg("jj", false), Seg("uː", true), Seg("n", false)),
            "يين" to listOf(Seg("i", true, 4), Seg("jj", false), Seg("iː", true), Seg("n", false)),
            "ية" to listOf(Seg("i", true, 4), Seg("jj", false), Seg("a", true), Seg("h", false)),
            "ين" to listOf(Seg("iː", true, 4), Seg("n", false), Seg("a", true)),
            "ون" to listOf(Seg("uː", true, 4), Seg("n", false), Seg("a", true)),
            "هما" to listOf(Seg("h", false), Seg("u", true, 4), Seg("m", false), Seg("aː", true)),
            "كما" to listOf(Seg("k", false), Seg("u", true, 4), Seg("m", false), Seg("aː", true)),
            "ها" to listOf(Seg("h", false), Seg("aː", true)),
            "هم" to listOf(Seg("h", false), Seg("u", true), Seg("m", false)),
            "هن" to listOf(Seg("h", false), Seg("u", true, 4), Seg("nn", false), Seg("a", true)),
            "كن" to listOf(Seg("k", false), Seg("u", true, 4), Seg("nn", false), Seg("a", true)),
            "وا" to listOf(Seg("uː", true)),
            "ه" to listOf(Seg("h", false)),
            "ك" to listOf(Seg("k", false), Seg("a", true)),
        )


        fun word(w: String, lexicon: Map<String, String>, dict: Map<String, Boolean>): String =
            render(stress(segs(w, lexicon, dict, 0)))

        /** Raw segments for a word: suffix stripping (espeak _S rules, stem looked up in the
         *  espeak dictionary first) + letter rules; stress is assigned once on the result. */
        fun segs(w: String, lexicon: Map<String, String>, dict: Map<String, Boolean>, depth: Int): List<Seg> {
            if (depth < 3) for ((suf, sfx) in SUFFIXES) {
                if (w.length >= suf.length + 1 && w.endsWith(suf)) {
                    val stem = w.substring(0, w.length - suf.length)
                    // espeak looks the stem up in its dictionary only for the outermost suffix
                    val stemSegs = if (depth == 0 && stem.length >= 2 && stem in dict && lexicon[stem] != null)
                        fromIpa(lexicon.getValue(stem), dict.getValue(stem))
                    else segs(stem, lexicon, dict, depth + 1)
                    return stemSegs + sfx.map { Seg(it.ipa, it.vowel, it.mark) }
                }
            }
            return letters(w)
        }

        /** Re-segment an espeak IPA string (dictionary entry). */
        fun fromIpa(ipa: String, explicitStress: Boolean): List<Seg> {
            val out = ArrayList<Seg>()
            var mark = -1
            var i = 0
            while (i < ipa.length) {
                val c = ipa[i]
                when {
                    c == 'ˈ' -> if (explicitStress) mark = 4  // computed stress is recomputed on stem+suffix
                    c == 'ˌ' -> {}
                    c == 'a' || c == 'i' || c == 'u' -> {
                        val long = i + 1 < ipa.length && ipa[i + 1] == 'ː'
                        out.add(Seg(if (long) "${c}ː" else "$c", true, mark)); mark = -1
                        if (long) i++
                    }
                    else -> out.add(Seg("$c", false))
                }
                i++
            }
            return out
        }

        fun letters(w: String): List<Seg> {
            val out = ArrayList<Seg>()
            var pendingMark = -1
            fun cons(s: String) { if (s.isNotEmpty()) out.add(Seg(s, false)) }
            fun vowel(s: String) { out.add(Seg(s, true, pendingMark)); pendingMark = -1 }
            var i = 0
            val n = w.length
            fun at(k: Int): Char = if (k in 0 until n) w[k] else '_'
            // previous base letter, skipping nothing (diacritics are letters for context, like espeak)
            while (i < n) {
                val c = w[i]
                val prev = at(i - 1)
                val next = at(i + 1)
                val initial = i == 0
                when (c) {
                    'ا' -> when {
                        next in HARAKAT -> cons("ʔ")
                        initial -> vowel("a")
                        else -> vowel("aː")
                    }
                    'آ' -> { cons("ʔ"); vowel("aː") }
                    'ى' -> if (next == '_' && prev in CONSONANT_LETTERS) vowel("aː") else vowel("a")
                    'و' -> when {
                        initial -> { cons("w"); pendingMark = 1 }  // espeak: _) و w%
                        prev == 'ا' || prev == SUKUN || prev == FATHA || next in HARAKAT -> cons("w")
                        next == SHADDA -> { cons("ww"); i++ }
                        prev == DAMMA -> vowel("uː")
                        prev in CONSONANT_LETTERS -> vowel("uː")
                        else -> cons("w")
                    }
                    'ي' -> when {
                        initial -> cons("j")
                        next == SHADDA -> { vowel("iː"); i++ }
                        next == KASRA -> { cons("j"); vowel("iː"); i++ }
                        prev == 'ا' || prev == SUKUN || prev == FATHA || next in HARAKAT -> cons("j")
                        prev == KASRA -> vowel("iː")
                        prev in CONSONANT_LETTERS -> vowel("iː")
                        else -> vowel("i")
                    }
                    'ن' -> { cons(if (next == 'ب' || (next == SUKUN && at(i + 2) == 'ب')) "m" else "n"); if (initial) pendingMark = -1 }
                    'ة' -> if (next == FATHATAN) { cons("t"); vowel("a"); cons("n"); i++ } else cons("t")
                    'ء' -> if (next == FATHATAN) { cons("ʔ"); vowel("a"); cons("n"); i++ } else cons("ʔ")
                    FATHA -> when {
                        next == 'ا' -> { vowel("aː"); i++ }
                        next == 'ى' -> { vowel("aː"); i++ }
                        next == 'و' && at(i + 2) !in HARAKAT && at(i + 2) != SHADDA -> { vowel("a"); vowel("u"); i++ }
                        next == 'ي' && at(i + 2) !in HARAKAT && at(i + 2) != SHADDA -> { vowel("a"); vowel("i"); i++ }
                        else -> vowel("a")
                    }
                    KASRA -> if (next == 'ي' && at(i + 2) !in HARAKAT) { vowel("iː"); i++ } else vowel("i")
                    DAMMA -> if (next == 'و' && at(i + 2) !in HARAKAT) { vowel("uː"); i++ } else vowel("u")
                    FATHATAN -> if (next == 'ا' && at(i + 2) == '_') { vowel("a"); cons("n"); i++ } else {}
                    DAMMATAN -> if (next == '_') { vowel("u"); cons("n") }
                    KASRATAN -> if (next == '_') { vowel("i"); cons("n") }
                    SHADDA -> {
                        // espeak 'C:' renders as Cː after stops, as a doubled consonant otherwise
                        val last = out.lastOrNull()
                        val base = lastLetter(w, i)
                        if (last == null || last.vowel || last.ipa.isEmpty() || base in LENGTHEN_COLON) cons("ː")
                        else cons(last.ipa)
                    }
                    SUPER_ALEF -> vowel("aː")
                    SUKUN, '\u0653', '\u0654', '\u0655', '\u06E1' -> {}
                    else -> {
                        val ipa = CONS[c]
                        if (ipa != null) {
                            if (c == 'ك' && next == '_' && n > 1) { cons("k"); vowel("a") }
                            else cons(ipa)
                            if (initial && c in INITIAL_UNSTRESSED) pendingMark = 1
                        }
                        // unknown characters are dropped
                    }
                }
                i++
            }
            if (pendingMark != -1) out.add(Seg("", false, pendingMark)) // carries over to a suffix vowel
            return out
        }

        /** espeak SetWordStress for STRESSPOSN_3R with default flags. */
        fun stress(input: List<Seg>): List<Pair<Seg, Int>> {
            val segs = ArrayList<Seg>()
            var carry = -1
            for (s in input) {
                if (!s.vowel && s.ipa.isEmpty()) { if (s.mark > carry) carry = s.mark; continue }
                if (s.vowel) { segs.add(if (carry != -1 && s.mark == -1) Seg(s.ipa, true, carry) else s); carry = -1 }
                else segs.add(s)
            }
            val vowels = segs.filter { it.vowel }
            val nV = vowels.size
            if (nV == 0) return segs.map { it to -1 }
            // vowel_stress[1..nV], sentinels at 0 and nV+1 are UNSTRESSED(1)
            val vs = IntArray(nV + 2) { -1 }; vs[0] = 1; vs[nV + 1] = 1
            var maxStress = -1; var primary = 0
            vowels.forEachIndexed { k, v ->
                val s = v.mark
                vs[k + 1] = s
                if (s > maxStress) maxStress = s
                if (s >= 4 && primary == 0) primary = k + 1
            }
            if (maxStress < 0) maxStress = 0 // STRESS_IS_DIMINISHED
            if (primary == 0) { // no explicit primary: antepenultimate
                val s = maxOf(1, nV - 2)
                if (maxStress == 0) vs[s] = 4
                maxStress = 4
            }
            var stress = if (maxStress < 4) 4 else 3
            for (v in 1..nV) {
                if (vs[v] < 0) {
                    if (vs[v - 1] <= 1 && (vs[v + 1] <= 1 || (stress == 4 && vs[v + 1] <= 2))) {
                        vs[v] = stress; stress = 3
                    }
                }
            }
            var k = 0
            return segs.map { s -> if (s.vowel) { k++; s to vs[k] } else s to -1 }
        }

        fun render(segs: List<Pair<Seg, Int>>): String {
            val sb = StringBuilder()
            for ((s, st) in segs) {
                if (s.vowel) { if (st >= 4) sb.append('ˈ') else if (st == 3) sb.append('ˌ') }
                sb.append(s.ipa)
            }
            // shadda after a consonant: espeak writes the geminate as Cː → keep; double ː collapse
            return sb.toString().replace("ːː", "ː")
        }
    }
